export const translate = (language, key, values = {}) =>
  (dictionary[language]?.[key] || dictionary.sk[key] || key).replace(/\{(\w+)\}/g, (_, name) => values[name] ?? '')
export const useTranslation = () => {
  const language = useSelector(state => state.fitness.language || 'sk')
  return {
    language,
    locale: locales[language] || locales.sk,
    t: (key, values) => translate(language, key, values),
    weekdays: dictionary[language]?.weekdays || dictionary.sk.weekdays,
  }
}
